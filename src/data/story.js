// ── 편지 종류 매핑 ────────────────────────────────────────────────────────
// 무작위가 아니라 해시여야 한다. Leitner가 같은 문제를 다시 내는데 종류가 매번 바뀌면
// "같은 편지가 돌아왔다"는 감각이 깨진다. 해시면 한 문제 = 한 통의 편지가 영구 고정.
export function parcelKindFor(id) {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  return PARCEL_KINDS[h % PARCEL_KINDS.length];
}
