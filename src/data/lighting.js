// ── 대기 원근 (§3) ──────────────────────────────────────────────────────────
// 수렴 비율은 지수 안개로 만든다. THREE.FogExp2는 1 − exp(−(d·k)²)라
// 근경은 거의 손대지 않고 원경만 빠르게 하늘색으로 간다 — 우리가 원하는 곡선이다.
//
// k는 "지평선(28u)에서 0.60 수렴"에서 역산했다:
//   1 − exp(−(28k)²) = 0.60  →  28k = 0.957  →  k = 0.0342
export const FOG_DENSITY = 0.0342;
export const HORIZON_U = 28;      // 카메라 고도 6.3u, R 68u 기준 지평선 거리

